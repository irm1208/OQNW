import {
  pgTable,
  serial,
  text,
  integer,
  numeric,
  timestamp,
  boolean,
  jsonb,
} from "drizzle-orm/pg-core";
import { createInsertSchema } from "drizzle-zod";
import { z } from "zod/v4";

export const ordersTable = pgTable("orders", {
  id: serial("id").primaryKey(),
  orderNumber: text("order_number").notNull().unique(),
  status: text("status").notNull().default("pending"),
  customerEmail: text("customer_email").notNull(),
  customerName: text("customer_name").notNull(),
  customerId: integer("customer_id"),
  phone: text("phone"),
  address1: text("address1"),
  address2: text("address2"),
  city: text("city"),
  county: text("county"),
  postcode: text("postcode"),
  country: text("country"),
  subtotalGbp: numeric("subtotal_gbp", { precision: 10, scale: 2 }).notNull().default("0"),
  bundleDiscountGbp: numeric("bundle_discount_gbp", { precision: 10, scale: 2 }).notNull().default("0"),
  shippingCostGbp: numeric("shipping_cost_gbp", { precision: 10, scale: 2 }).notNull().default("0"),
  taxAmountGbp: numeric("tax_amount_gbp", { precision: 10, scale: 2 }).notNull().default("0"),
  totalGbp: numeric("total_gbp", { precision: 10, scale: 2 }).notNull().default("0"),
  paymentCurrency: text("payment_currency"),
  paymentAmountMinor: integer("payment_amount_minor"),
  cryptoPaymentStatus: text("crypto_payment_status").notNull().default("not_applicable"),
  cryptoCurrency: text("crypto_currency"),
  cryptoNetwork: text("crypto_network"),
  cryptoWalletAddress: text("crypto_wallet_address"),
  cryptoRouteSnapshot: jsonb("crypto_route_snapshot").$type<Record<string, unknown> | null>(),
  cryptoExpectedAmount: numeric("crypto_expected_amount", { precision: 30, scale: 18 }),
  cryptoRateUsd: numeric("crypto_rate_usd", { precision: 30, scale: 10 }),
  cryptoRateLockedAt: timestamp("crypto_rate_locked_at", { withTimezone: true }),
  cryptoRateExpiresAt: timestamp("crypto_rate_expires_at", { withTimezone: true }),
  cryptoPaymentAccessToken: text("crypto_payment_access_token"),
  cryptoTxHash: text("crypto_tx_hash"),
  cryptoObservedAmount: numeric("crypto_observed_amount", { precision: 30, scale: 18 }),
  cryptoConfirmations: integer("crypto_confirmations"),
  cryptoConfirmedAt: timestamp("crypto_confirmed_at", { withTimezone: true }),
  cryptoLastCheckedAt: timestamp("crypto_last_checked_at", { withTimezone: true }),
  cryptoPaymentReason: text("crypto_payment_reason"),
  refundedAmountGbp: numeric("refunded_amount_gbp", { precision: 10, scale: 2 }).notNull().default("0"),
  refundStatus: text("refund_status").notNull().default("none"),
  shippingMethod: text("shipping_method"),
  shippingRateId: integer("shipping_rate_id"),
  carrierName: text("carrier_name"),
  trackingNumber: text("tracking_number"),
  trackingUrl: text("tracking_url"),
  dispatchedAt: timestamp("dispatched_at", { withTimezone: true }),
  notes: text("notes"),
  fraudScore: integer("fraud_score").notNull().default(0),
  fraudFlags: text("fraud_flags").array().notNull().default([]),
  fraudReviewed: boolean("fraud_reviewed").notNull().default(false),
  fraudReviewNote: text("fraud_review_note"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow().$onUpdate(() => new Date()),
  reviewRequestSentAt: timestamp("review_request_sent_at", { withTimezone: true }),
});

export const insertOrderSchema = createInsertSchema(ordersTable).omit({
  id: true,
  createdAt: true,
  updatedAt: true,
});

export type InsertOrder = z.infer<typeof insertOrderSchema>;
export type Order = typeof ordersTable.$inferSelect;
